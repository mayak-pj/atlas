"""Уровни изображения и приоритеты очереди. Таблица уровней — в docs/ARCHITECTURE.md."""
from __future__ import annotations

L0 = 0  # миниатюра, сторона ~160 px
L1 = 1  # превью, 1/4
L2 = 2  # половина
L3 = 3  # полное
LEVELS = (L0, L1, L2, L3)
DISK_LEVELS = (L0, L1)  # остальные на диск не пишем: они большие и быстро вытеснили бы превью

CURRENT = 0  # то, на что смотрят
NEIGHBOR = 1
WARMUP = 2  # прогрев папки на локальный диск

_DIVISORS = {L1: 4, L2: 2, L3: 1}


def level_divisor(level):
    """Во сколько раз уровень L1–L3 меньше исходника."""
    return _DIVISORS[level]


def level_for_scale(scale):
    """Наименьший уровень, в котором на один пиксель экрана приходится не меньше одного пикселя картинки.

    scale — пикселей экрана на пиксель исходника. L0 здесь нет: он для ленты миниатюр.
    """
    if scale <= 0.25:
        return L1
    return L2 if scale <= 0.5 else L3


def scaled_size(width, height, level):
    """Размер декодирования для L1–L3.

    Округление только вниз: qjpeg выбирает делитель DCT как исходный размер // заданный. Округление вверх
    у нечётных размеров (3457 → 865) дало бы 3457 // 865 = 3: декодирование в 1/2 и пересчёт, в разы дольше.
    """
    divisor = _DIVISORS[level]
    return max(1, width // divisor), max(1, height // divisor)

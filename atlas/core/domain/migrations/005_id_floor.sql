-- Папку можно удалить из Atlas (04.11.2026). SQLite отдаёт новой строке номер max(id) + 1, то есть номер
-- только что удалённой последней папки или фото — и к новой папке прилипли бы чужие черновик, журнал раскладки,
-- комментарии (они хранят номер). Здесь — самый большой номер, который уже был; новые строки получают номер выше.
CREATE TABLE id_floor (
    tbl TEXT PRIMARY KEY,
    max_id INTEGER NOT NULL
);
